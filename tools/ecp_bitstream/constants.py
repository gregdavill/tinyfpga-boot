#: LSC_PROG_CNTRL0 base: master SPI enabled (bit 30). The low byte selects the
#: SPI read clock — OR in one of SPI_FREQ_MHZ.
_CNTRL0_BASE = 0x40000000

#: SPI read-clock divider codes (CNTRL0 low byte)
SPI_FREQ_MHZ = {
    2.4:  0x00,
    4.8:  0x01,
    9.7:  0x20,
    19.4: 0x30,
    38.8: 0x38,
    62.0: 0x3b,
}

#: Default read clock
DEFAULT_SPI_FREQ = 38.8


def prog_cntrl0(freq_mhz=DEFAULT_SPI_FREQ):
    """CNTRL0 value for an SPI read clock (MHz; one of SPI_FREQ_MHZ)."""
    return _CNTRL0_BASE | SPI_FREQ_MHZ[freq_mhz]


